#!/bin/zsh
# Creates Recall.app (start or open Recall) and "Stop Recall.app" in /Applications.
# Re-run this script if you move the project folder.
#
#   DEST=/some/folder zsh scripts/make-mac-app.sh   # write the apps somewhere else (used by the tests)
#   RECALL_SKIP_ICON=1                              # skip icon generation (used by the tests)
set -e
PROJECT="$(cd "$(dirname "$0")/.." && pwd)"
DEST="${DEST:-/Applications}"

make_icon() { # app path — builds AppIcon.icns from public/favicon.svg
  local tmp="$(mktemp -d)"; local set="$tmp/AppIcon.iconset"
  mkdir -p "$set" "$1/Contents/Resources"
  # Shrink the logo inside the canvas so it matches the size of other macOS icons.
  sed 's/viewBox="0 0 64 64"/viewBox="-7.75 -7.75 79.5 79.5"/' "$PROJECT/public/favicon.svg" > "$tmp/icon.svg"
  qlmanage -t -s 1024 -o "$tmp" "$tmp/icon.svg" >/dev/null 2>&1
  for s in 16 32 128 256 512; do
    sips -z $s $s "$tmp/icon.svg.png" --out "$set/icon_${s}x${s}.png" >/dev/null
    sips -z $((s*2)) $((s*2)) "$tmp/icon.svg.png" --out "$set/icon_${s}x${s}@2x.png" >/dev/null
  done
  iconutil -c icns "$set" -o "$1/Contents/Resources/AppIcon.icns"
  rm -rf "$tmp"
}

# Shared by both apps: find a Node.js that can run Recall (≥ 22.18 runs TypeScript natively),
# and explain in a native dialog when there is none.
read -r -d '' PRELUDE <<'EOF' || true
LOG="$HOME/Library/Logs/Recall.log"
mkdir -p "${LOG:h}"
NODE="" FOUND_OLD=""

node_ok() { # node binary → success if it is Node.js 22.18 or newer
  local v major minor
  v="$("$1" -v 2>/dev/null)" || return 1
  v="${v#v}"; major="${v%%.*}"; minor="${${v#*.}%%.*}"
  [[ "$major" == <-> && "$minor" == <-> ]] || return 1
  (( major > 22 || (major == 22 && minor >= 18) ))
}

find_node() {
  local -a candidates
  local c
  if [[ -n "$RECALL_NODE_CANDIDATES" ]]; then
    candidates=(${(s.:.)RECALL_NODE_CANDIDATES})
  else
    c="$(command -v node 2>/dev/null)" && candidates+=("$c")
    candidates+=(
      /opt/homebrew/opt/node@24/bin/node /opt/homebrew/bin/node
      /usr/local/opt/node@24/bin/node /usr/local/bin/node
      "$HOME/.volta/bin/node"
      "$HOME/Library/Application Support/fnm/aliases/default/bin/node"
      "$HOME/.local/share/fnm/aliases/default/bin/node"
      "$HOME/.fnm/aliases/default/bin/node"
    )
    if [[ -r "$HOME/.nvm/alias/default" ]]; then
      local nvm_default="$(<"$HOME/.nvm/alias/default")"
      candidates+=("$HOME"/.nvm/versions/node/v${nvm_default#v}*/bin/node(N))
    fi
    candidates+=("$HOME"/.nvm/versions/node/*/bin/node(NOn))
  fi
  for c in $candidates; do
    [[ -x "$c" ]] || continue
    if node_ok "$c"; then NODE="$c"; return 0; fi
    [[ -z "$FOUND_OLD" ]] && FOUND_OLD="$("$c" -v 2>/dev/null)"
  done
  return 1
}

dialog() { # message, buttons… → prints the chosen button
  local msg="$1"; shift
  local buttons="" b
  for b in "$@"; do buttons+="${buttons:+, }\"$b\""; done
  osascript -e 'on run argv' \
    -e "display dialog (item 1 of argv) with title \"Recall\" buttons {$buttons} default button \"${@[-1]}\" with icon caution" \
    -e 'end run' "$msg" 2>/dev/null
}

node_missing() {
  local why
  if [[ -n "$FOUND_OLD" ]]; then
    why="Recall needs Node.js 24 to run. This Mac has Node.js ${FOUND_OLD#v}, which is too old."
  else
    why="Recall needs Node.js 24 to run, and it is not installed on this Mac."
  fi
  echo "[app $(date '+%Y-%m-%d %H:%M:%S')] ${why}" >> "$LOG"
  local answer="$(dialog "${why}

To install it, download Node.js 24 LTS from nodejs.org and open the installer. If you use Homebrew, you can run this command in Terminal instead:

brew install node@24

Then open Recall again." "Open download page" "OK")"
  [[ "$answer" == *"Open download page"* ]] && open "https://nodejs.org/en/download"
  return 0
}

cd "$PROJECT" 2>/dev/null || {
  dialog "Recall could not find its folder:
$PROJECT

If you moved it, run scripts/make-mac-app.sh again from the new location." "OK" >/dev/null
  exit 1
}
EOF

make_app() { # name, body
  local app="$DEST/$1.app"
  rm -rf "$app"
  mkdir -p "$app/Contents/MacOS"
  cat > "$app/Contents/Info.plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>CFBundleName</key><string>$1</string>
  <key>CFBundleExecutable</key><string>launch</string>
  <key>CFBundleIdentifier</key><string>local.recall.$(echo "$1" | tr -d ' ' | tr A-Z a-z)</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>LSUIElement</key><true/>
  <key>CFBundleIconFile</key><string>AppIcon</string>
</dict></plist>
EOF
  [[ "$RECALL_SKIP_ICON" == 1 ]] || make_icon "$app"
  { print -r -- '#!/bin/zsh'
    print -r -- "# Generated by scripts/make-mac-app.sh. Re-run it if you move the project folder."
    print -r -- "PROJECT=${(q)PROJECT}"
    print -r -- "$PRELUDE"
    print -r -- "$2"
  } > "$app/Contents/MacOS/launch"
  chmod +x "$app/Contents/MacOS/launch"
}

# The launcher reuses a healthy Recall, replaces a stale one, rebuilds after updates and
# shows a status page in the browser; it only returns non-zero when no page can explain the problem.
make_app "Recall" '
find_node || { node_missing; exit 1; }
MSG="$(mktemp -t recall)"
RECALL_MESSAGE_FILE="$MSG" "$NODE" server/launcher.ts >> "$LOG" 2>&1
code=$?
if (( code != 0 )); then
  text="$(<"$MSG")"
  [[ -n "$text" ]] || text="Recall could not start."
  answer="$(dialog "$text

Details are in the log: $LOG" "Open log" "OK")"
  [[ "$answer" == *"Open log"* ]] && open "$LOG"
fi
rm -f "$MSG"
exit $code
'

make_app "Stop Recall" '
notify() { osascript -e "on run argv" -e "display notification (item 1 of argv) with title \"Recall\"" -e "end run" "$1" 2>/dev/null; }
find_node || { notify "Recall could not be stopped: Node.js 24 was not found."; exit 1; }
MSG="$(mktemp -t recall)"
RECALL_MESSAGE_FILE="$MSG" "$NODE" server/launcher.ts --stop >> "$LOG" 2>&1
code=$?
text="$(<"$MSG")"
[[ -n "$text" ]] || text="Recall could not be stopped. Details are in $LOG."
notify "$text"
rm -f "$MSG"
exit $code
'

echo "Created $DEST/Recall.app and $DEST/Stop Recall.app"

import type { CardRender, NoteFields, NoteKind, NoteOptions, NoteTemplateDef } from './notes.ts';
import type { LocalDate } from './dates.ts';
import type { QueueProgress } from './queue.ts';
import type { Rating, StudyMode } from './ratings.ts';
import type { AppSettings } from './settings.ts';

export type Level = 'program' | 'semester' | 'course' | 'section';
export type TrashType = Level | 'card';

interface Lifecycle {
  isDemo: boolean;
  archivedAt: string | null;
  deletedAt: string | null;
  createdAt: string;
  updatedAt: string;
}

export interface Program extends Lifecycle {
  id: string;
  title: string;
  description: string;
  position: number;
}

export interface Semester extends Lifecycle {
  id: string;
  programId: string;
  title: string;
  startDate: LocalDate | null;
  endDate: LocalDate | null;
  position: number;
}

export interface Course extends Lifecycle {
  id: string;
  semesterId: string;
  title: string;
  moduleCode: string;
  color: string;
  icon: string;
  description: string;
  examDate: LocalDate | null;
  examSetAt: string | null;
  position: number;
}

export type SectionKind = 'lecture' | 'tutorial' | 'revision' | 'reading' | 'other';

export interface Section extends Lifecycle {
  id: string;
  courseId: string;
  title: string;
  kind: SectionKind;
  weekNumber: number | null;
  date: LocalDate | null;
  notes: string;
  position: number;
}

export interface Counts {
  total: number;
  due: number;
  new: number;
  suspended: number;
}

export interface TreeSection extends Section {
  counts: Counts;
}
export interface TreeCourse extends Course {
  counts: Counts;
  sections: TreeSection[];
}
export interface TreeSemester extends Semester {
  counts: Counts;
  courses: TreeCourse[];
}
export interface TreeProgram extends Program {
  counts: Counts;
  semesters: TreeSemester[];
}

export interface Crumb {
  id: string;
  title: string;
  level: Level;
}

export type CardStatus = 'new' | 'due' | 'scheduled' | 'suspended';

export interface CardSchedule {
  dueDate: LocalDate;
  intervalDays: number;
  reviewCount: number;
  lapseCount: number;
  lastRating: Rating;
  firstReviewedAt: string;
  lastReviewedAt: string;
  schedulerVersion: string;
}

export interface Card {
  id: string;
  sectionId: string;
  courseId: string;
  front: string;
  back: string;
  explanation: string;
  hint: string;
  source: string;
  bookmarked: boolean;
  suspendedAt: string | null;
  position: number;
  revision: number;
  isDemo: boolean;
  tags: string[];
  createdAt: string;
  updatedAt: string;
  schedule: CardSchedule | null;
  status: CardStatus;
  /** Latest recorded (non-undone) rating in any mode, or null if never rated. */
  lastRating: Rating | null;
  lastRatingMode: StudyMode | null;
  sectionTitle: string;
  courseTitle: string;
  /** The note this card was generated from, and which of its variants it is. */
  noteId: string;
  kind: NoteKind;
  variant: string;
  /** e.g. "Reverse", "Cloze 2", "Box: Femur" — '' for a plain basic card. */
  variantLabel: string;
  /** Live cards generated by the same note, this one included. */
  siblingCount: number;
}

export interface NoteCardSummary {
  id: string;
  variant: string;
  label: string;
  status: CardStatus;
  dueDate: string | null;
  reviewCount: number;
  /** A gap, box or card type the note no longer has; hidden but its history is kept. */
  retired: boolean;
  suspended: boolean;
}

export interface Note {
  id: string;
  sectionId: string;
  kind: NoteKind;
  templateId: string | null;
  fields: NoteFields;
  options: NoteOptions;
  tags: string[];
  /** True when every live card of the note is bookmarked. */
  bookmarked: boolean;
  revision: number;
  createdAt: string;
  updatedAt: string;
  cards: NoteCardSummary[];
}

export interface NoteSaveResult {
  note: Note;
  /** The note's first live card (the editor route uses card ids). */
  primaryCardId: string;
  sync: { created: number; updated: number; retired: number; restored: number };
}

export interface NoteTemplate extends NoteTemplateDef {
  isDemo: boolean;
  archivedAt: string | null;
  createdAt: string;
  updatedAt: string;
  usage: { notes: number; cards: number };
}

export interface TemplateImpact {
  notes: number;
  created: number;
  updated: number;
  retired: number;
  restored: number;
  /** Notes whose fields no longer fill any card front (all their cards are retired). */
  notesWithoutCards: number;
}

export interface CardInput {
  sectionId: string;
  front: string;
  back: string;
  explanation?: string;
  hint?: string;
  source?: string;
  tags?: string[];
  bookmarked?: boolean;
}

export type CardFilter = 'all' | 'new' | 'due' | 'notDue' | 'weak' | 'bookmarked' | 'suspended';

export interface CardListResponse {
  cards: Card[];
  total: number;
}

export interface MediaAsset {
  id: string;
  filename: string;
  url: string;
  mimeType: string;
  sizeBytes: number;
  originalName: string;
}

// ---------- Sessions ----------

export type SessionOrdering = 'default' | 'random' | 'weakest';
export type WeakBasis = 'all' | 'scheduled';

export interface SessionScope {
  /** Explicit section IDs, course IDs, or a semester. Union of all given. */
  sectionIds?: string[];
  courseIds?: string[];
  semesterId?: string | null;
  /** Explicit card list (e.g. "review weak cards" after a session). */
  cardIds?: string[];
}

export interface SessionFilters {
  includeNew: boolean;
  tags: string[];
  bookmarkedOnly: boolean;
  /** Practice/test status filter. */
  status: 'any' | 'new' | 'due' | 'notDue' | 'weak' | 'reviewed';
  weakBasis: WeakBasis;
  /**
   * At most one card per note in a session (default on), so a reverse card or another
   * cloze gap of the same note doesn't give away the answer right after.
   */
  oneCardPerNote?: boolean;
}

export interface SessionRequest {
  mode: StudyMode;
  scope: SessionScope;
  filters: SessionFilters;
  ordering: SessionOrdering;
  size: number;
  maxAttempts: number;
  seed?: number;
  title?: string;
  /** Required to start when fewer cards are available than requested. */
  acceptSmaller?: boolean;
}

export interface ScopeSummaryItem {
  id: string;
  title: string;
  level: Level;
}

export interface SessionPreview {
  scopeLabel: string;
  scopeItems: ScopeSummaryItem[];
  /** Counts of all study-eligible (non-suspended, non-archived) cards in scope. */
  breakdown: {
    total: number;
    due: number;
    new: number;
    notYetDue: number;
    weak: number;
    neverReviewed: number;
    suspended: number;
  };
  /** Cards matching mode + filters. */
  available: number;
  requested: number;
  willSelect: number;
  /** Composition of the cards that would be selected. */
  selection: { due: number; new: number; notYetDue: number };
}

export type SessionStatus = 'active' | 'paused' | 'completed' | 'ended';

export interface CardSnapshot {
  front: string;
  back: string;
  explanation: string;
  hint: string;
  source: string;
  tags: string[];
  sectionTitle: string;
  courseTitle: string;
  courseColor: string;
  /** How to draw the card; absent for sessions started before card types existed. */
  render?: CardRender;
  variantLabel?: string;
}

export interface SessionSummary {
  id: string;
  mode: StudyMode;
  status: SessionStatus;
  title: string;
  scopeLabel: string;
  startedAt: string;
  updatedAt: string;
  finishedAt: string | null;
  activeMs: number;
  progress: QueueProgress;
}

export interface SessionState extends SessionSummary {
  revision: number;
  maxAttempts: number;
  ordering: SessionOrdering;
  revealed: boolean;
  hintShown: boolean;
  typedAnswer: string;
  waiting: boolean;
  relaxed: boolean;
  current: {
    cardId: string;
    attempt: number;
    isRepeat: boolean;
    snapshot: CardSnapshot;
    /** Short excerpt shown when a card was edited after the session began. */
    editedSinceStart: boolean;
  } | null;
  canUndo: boolean;
  lastRating: { cardId: string; rating: Rating; front: string } | null;
}

export interface SessionResultCard {
  cardId: string;
  front: string;
  sectionId: string;
  sectionTitle: string;
  courseTitle: string;
  attempts: number;
  firstRating: Rating | null;
  finalRating: Rating | null;
  status: 'pending' | 'completed' | 'unresolved';
}

export interface SessionResults {
  session: SessionSummary;
  firstRatingCounts: Record<Rating, number>;
  finalRatingCounts: Record<Rating, number>;
  repeatAttempts: number;
  notReached: number;
  cards: SessionResultCard[];
  bySection: {
    sectionId: string;
    sectionTitle: string;
    courseTitle: string;
    cards: number;
    firstRecalled: number;
    unresolved: number;
    attempts: number;
  }[];
  weakCardIds: string[];
}

